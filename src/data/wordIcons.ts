const CHAPTER_FALLBACK_ICON: Record<string, WordIconKey> = {
  'office-hr': 'briefcase',
  meetings: 'people',
  travel: 'plane',
  finance: 'money',
  marketing: 'megaphone',
}

export function getWordIcon(wordId: string): WordIconKey {
  const direct = WORD_ICONS[wordId]
  if (direct) return direct
  const chapterId = wordId.split('-')[0]
  const prefixToChapter: Record<string, string> = {
    ohr: 'office-hr',
    mtg: 'meetings',
    trv: 'travel',
    fin: 'finance',
    mkt: 'marketing',
  }
  return CHAPTER_FALLBACK_ICON[prefixToChapter[chapterId] ?? ''] ?? 'document'
}
